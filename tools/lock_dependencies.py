"""Snapshot the installed Linux/Python 3.14 release-test dependency closure.

Run in the verified environment after installing backend_python[dev,web,vision].
No index URLs, credentials, local paths, or unrelated installed packages are saved.
"""

import argparse
from importlib.metadata import distribution
from pathlib import Path
import platform
import sys

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name


def snapshot():
    if platform.system() != "Linux" or sys.version_info[:2] != (3, 14):
        raise SystemExit("This lock targets Linux CPython 3.14; regenerate on that baseline.")
    environment = default_environment()
    pending = [("blob-backend", frozenset({"dev", "web", "vision"}))]
    visited, pinned = set(), {}
    while pending:
        name, extras = pending.pop()
        name = canonicalize_name(name)
        if (name, extras) in visited:
            continue
        visited.add((name, extras))
        package = distribution(name)
        if name != "blob-backend":
            pinned[name] = package.version
        for value in package.requires or ():
            requirement = Requirement(value)
            if requirement.marker and not any(requirement.marker.evaluate({**environment, "extra": extra})
                                              for extra in {"", *extras}):
                continue
            dependency = distribution(requirement.name)
            if requirement.url or not requirement.specifier.contains(dependency.version, prereleases=True):
                raise SystemExit(f"Installed dependency does not satisfy {requirement.name}; resolve before locking.")
            pending.append((requirement.name, frozenset(requirement.extras)))
    header = ("# Linux CPython 3.14 release-test environment: backend [dev,web,vision].\n"
              "# Generated by tools/lock_dependencies.py from the tested dependency closure.\n"
              "# Version pins only; hashes and native OS packages are not locked here.\n")
    return header + "".join(f"{name}=={version}\n" for name, version in sorted(pinned.items()))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("requirements/linux-py314.lock"))
    parser.add_argument("--check", action="store_true", help="Fail if installed dependencies differ from the lock")
    args = parser.parse_args()
    content = snapshot()
    if args.check:
        if not args.output.is_file() or args.output.read_text() != content:
            raise SystemExit("Release dependencies differ from the lock. Resolve and re-test before regenerating it.")
        print("Release dependency versions match the lock.")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(content)
        print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
